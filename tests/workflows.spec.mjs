const tab = (page, name) => page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name })
const button = (root, name) => root.getByRole('button', { name, exact: true })
const dialog = page => page.getByRole('dialog')
const status = (page, text) => expect(page.locator('#notice')).toContainText(text)
async function go(page, name) {
  await tab(page, name).click()
  await expect(page.getByRole('heading', { name, exact: true, level: 1 })).toBeVisible()
}
async function steps(page, count, edit = false) {
  await button(page, edit ? 'Edit steps' : 'Enter steps').click()
  await dialog(page).getByLabel('Daily steps').fill(String(count))
  await button(dialog(page), 'Save steps').click()
  await expect(dialog(page)).toHaveCount(0)
}
async function rice(page, amount) {
  await go(page, 'Food')
  await page.getByRole('searchbox').fill('nasi putih')
  await expect(page.getByText(/Cooked · long-grain/)).toBeVisible()
  await button(page, 'Add White rice').click()
  await dialog(page).getByLabel('Portion', { exact: true }).fill(String(amount))
  await button(dialog(page), 'Add to diary').click()
  await expect(dialog(page)).toHaveCount(0)
}
async function workout(page) {
  await go(page, 'Training')
  await page.locator('.template').filter({ hasText: 'Upper A' }).getByRole('button', { name: 'Start', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Upper A', level: 2 })).toBeVisible()
  const first = page.locator('.exercise-row').filter({ hasText: 'Dumbbell bench press' })
  await button(first, 'Log set').click()
  await dialog(page).getByLabel('Actual kg').fill('17.5')
  await dialog(page).getByLabel('Reps').fill('10')
  await dialog(page).getByLabel('Warm-up').uncheck()
  await button(dialog(page), 'Save set').click()
  await expect(dialog(page)).toHaveCount(0)
  await expect(first).toContainText('17.5 kg × 10 reps')
}
async function getBackup(page) {
  await page.getByRole('link', { name: 'Settings' }).click()
  await button(page, 'Export backup').click()
  const downloaded = page.waitForEvent('download')
  await button(dialog(page), 'Download JSON').click()
  const file = await downloaded
  const data = JSON.parse(await readFile(await file.path(), 'utf8'))
  await button(dialog(page), 'Close dialog').click()
  return data
}
async function previewBackup(page, data) {
  await page.getByRole('link', { name: 'Settings' }).click()
  await button(page, 'Import backup').click()
  await dialog(page).getByLabel('Backup file').setInputFiles({
    name: 'synthetic.json', mimeType: 'application/json',
    buffer: Buffer.from(typeof data === 'string' ? data : JSON.stringify(data)),
  })
  await button(dialog(page), 'Preview backup').click()
}

