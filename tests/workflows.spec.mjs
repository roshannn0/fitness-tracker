test('recipe edits preserve logs, exports round-trip and reject corrupt backups', async ({ page, browser }, testInfo) => {
  await page.goto('./')
  await go(page, 'Food')
  await button(page, 'Recipes').click()
  await button(page, 'Create recipe batch').click()
  await dialog(page).getByLabel('Recipe name').fill('Synthetic batch')
  await dialog(page).getByLabel('Final batch yield').fill('300')
  await dialog(page).getByLabel('Edible grams').fill('150')
  await button(dialog(page), 'Add ingredient').click()
  await button(dialog(page), 'Save recipe batch').click()
  await button(page, 'Add Synthetic batch').click()
  await dialog(page).getByLabel('Portion (g)').fill('150')
  await button(dialog(page), 'Add recipe portion').click()
  await expect(dialog(page)).toHaveCount(0)
  await button(page, 'Add Synthetic batch').click()
  await button(dialog(page), 'Edit recipe').click()
  await dialog(page).getByLabel('Final batch yield').fill('600')
  await button(dialog(page), 'Save recipe batch').click()
  await expect(dialog(page)).toHaveCount(0)
  await go(page, 'Today')
  await expect(page.locator('.target-main').first()).toHaveText(/98/)
  await steps(page, 3210)
  await workout(page)
  const saved = await getBackup(page)
  expect(saved.days).toHaveLength(1)
  expect(saved.sessions).toHaveLength(1)
  expect(saved.profile.recipes[0].yield.amount).toBe(600)
  expect(saved.days[0].meals[0].entries[0].nutrients.kcal).toBe(97.5)

  const clean = await browser.newContext({ baseURL: testInfo.project.use.baseURL, timezoneId: 'Pacific/Honolulu' })
  try {
    const destination = await clean.newPage()
    await destination.goto('./')
    await previewBackup(destination, saved)
    await expect(dialog(destination)).toContainText(saved.days[0].date)
    await button(dialog(destination), 'Replace with this backup').click()
    const roundTrip = await getBackup(destination)
    expect({ ...roundTrip, exportedAt: saved.exportedAt }).toEqual(saved)
    for (const [invalid, message] of [['{!}', 'valid JSON'], [{ ...saved, schemaVersion: 2 }, 'newer version']]) {
      await previewBackup(destination, invalid)
      await expect(dialog(destination).getByRole('alert')).toContainText(message)
      await button(dialog(destination), 'Close dialog').click()
    }
    const intact = await getBackup(destination)
    expect({ ...intact, exportedAt: saved.exportedAt }).toEqual(saved)
  } finally { await clean.close() }
})

test('failed transaction is visible and can be retried without changing the existing value', async ({ page }) => {
  await page.goto('./')
  await steps(page, 1200)
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args) {
      IDBObjectStore.prototype.put = original
      throw new DOMException('Simulated write failure', 'QuotaExceededError')
    }
  })
  await button(page, 'Edit steps').click()
  await dialog(page).getByLabel('Daily steps').fill('5500')
  await button(dialog(page), 'Save steps').click()
  await expect(dialog(page).getByText('Could not save locally. Try again.')).toBeVisible()
  await button(dialog(page), 'Close dialog').click()
  await expect(page.getByText('1,200', { exact: true })).toBeVisible()
  await steps(page, 5500, true)
  await expect(page.getByText('5,500', { exact: true })).toBeVisible()
})

test('one year of synthetic logs remains usable and private in a fresh session', async ({ page }) => {
  const entry = foodPortion(starterFoods[0], 150, 'g')
  const days = Array.from({ length: 365 }, (_, index) => {
    const date = new Date(Date.UTC(2025, 0, index + 1)).toISOString().slice(0, 10)
    return { ...blankDay(date), steps: 3000 + index, complete: index % 2 === 0,
      meals: [{ id: 'sample-' + index, name: 'Synthetic lunch', slot: 'Lunch', entries: [entry], time: '12:30', created: date + 'T04:30:00.000Z' }] }
  })
  const backup = { schemaVersion: 1, exportedAt: new Date().toISOString(), profile: newProfile(), days, sessions: [] }
  await page.goto('./')
  await previewBackup(page, backup)
  await expect(dialog(page)).toContainText('365 days · 365 meals')
  await button(dialog(page), 'Replace with this backup').click()
  await go(page, 'Today')
  await page.getByRole('button', { name: /^Choose log date/ }).click()
  await dialog(page).getByLabel('Log date').fill('2025-12-31')
  await button(dialog(page), 'Open selected date').click()
  await expect(page.getByRole('heading', { name: 'Synthetic lunch' })).toBeVisible()
  await go(page, 'Progress')
  await expect(page.getByText('intake days marked complete')).toBeVisible()
  await expect(page.getByText('Compared with', { exact: false })).toBeVisible()
  await go(page, 'Food')
  await page.getByRole('searchbox').fill('nasi putih')
  await expect(page.getByText(/Cooked · long-grain/)).toBeVisible()
})

test('applying a prepared update preserves a meal and unfinished workout', async ({ page, request }) => {
  await page.goto('./')
  await expect(page.getByText('Available offline')).toBeVisible()
  await rice(page, 150)
  await workout(page)
  await request.post('/__test_update')
  try {
    await page.evaluate(async () => (await navigator.serviceWorker.getRegistration())?.update().then(() => undefined))
    await expect(button(page, 'Reload and update')).toBeVisible({ timeout: 15000 })
    await button(page, 'Reload and update').click()
    await expect(page.locator('meta[name=test-release]')).toHaveAttribute('content', 'updated')
    await expect(page.getByText('17.5 kg × 10 reps', { exact: false })).toBeVisible()
    await go(page, 'Today')
    await expect(page.locator('.target-main').first()).toHaveText(/195/)
    await expect(button(page, 'Resume workout')).toBeVisible()
  } finally { await request.post('/__test_update') }
})

